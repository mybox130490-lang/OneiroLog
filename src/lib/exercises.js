export function randomQuests(count = 3) {
  const pool = [...ATTENTION_QUESTS]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool.slice(0, count).map((text) => ({
    id: makeId(),
    kind: 'quest',
    focus: 'свежий взгляд',
    basedOn: 'квест внимания',
    targetCount: 1,
    text
  }))
}

// Генерирует приоритетное упражнение + альтернативы на основе паттернов.
export function generateExercises(patterns) {
  const out = []

  // 1) Доминирующая негативная серия → контр-упражнение
  const negStreak = (patterns.streaks || []).find(
    (s) => s.category === 'emotion' && NEGATIVE.has(s.word)
  )
  if (negStreak) {
    const opp = OPPOSITES[negStreak.word] || 'противоположного состояния'
    out.push({
      id: makeId(),
      kind: 'counter',
      focus: opp,
      basedOn: `серия: ${negStreak.text}`,
      targetCount: 3,
      text: `Ты несколько дней подряд замечал «${negStreak.word}». Это колея внимания, а не вся правда дня. Завтра найди ровно три момента ${opp} — и запиши их, даже если они мелкие.`
    })
  }

  // 2) Слепая зона → упражнение-восполнение
  const zone = (patterns.blindZones || [])[0]
  if (zone && BLIND_ZONE_TASKS[zone.key]) {
    out.push({
      id: makeId(),
      kind: 'blindzone',
      focus: zone.label,
      basedOn: `слепая зона: ${zone.label}`,
      targetCount: 3,
      text: `Категория «${zone.label}» почти не появляется в твоих записях — сознание её обходит. ${BLIND_ZONE_TASKS[zone.key]}`
    })
  }

  // 3) Повторяющийся образ → наблюдение
  const topImage = (patterns.topImages || [])[0]
  if (topImage && topImage.weight >= 2) {
    const observe =
      IMAGE_OBSERVE[topImage.word] ||
      `Понаблюдай за образом «${topImage.word}»: где он появляется наяву и что прячется за ним?`
    out.push({
      id: makeId(),
      kind: 'observe',
      focus: topImage.word,
      basedOn: `повторяющийся образ: ${topImage.word}`,
      targetCount: 3,
      text: `Образ «${topImage.word}» повторяется чаще других. ${observe}`
    })
  }

  // 4) Фоллбэк — базовое упражнение на замечание
  if (out.length === 0) {
    out.push({
      id: makeId(),
      kind: 'baseline',
      focus: 'детали',
      basedOn: 'недостаточно данных для паттернов',
      targetCount: 3,
      text: 'Завтра поймай три детали, которые обычно ускользают: звук, запах, оттенок света. Запиши их вечером.'
    })
  }

  return out
}

// Замер эффекта: сравнивает направленность 7 дней ДО и 7 дней ПОСЛЕ задания.
export function measureExerciseEffect(exercise, allEntries) {
  const created = (exercise.createdAt || '').slice(0, 10)
  if (!created) return null
  const createdMs = Date.parse(created)
  const DAY = 86400000

  const before = allEntries.filter((e) => {
    const d = Date.parse(e.date)
    return d < createdMs && d >= createdMs - 7 * DAY
  })
  const after = allEntries.filter((e) => {
    const d = Date.parse(e.date)
    return d >= createdMs && d <= createdMs + 7 * DAY
  })

  if (before.length === 0 || after.length === 0) {
    return { ready: false, before: before.length, after: after.length }
  }

  const di1 = directionIndex(before)
  const di2 = directionIndex(after)
  const delta = Math.round((di2.score - di1.score) * 100) / 100
  return {
    ready: true,
    beforeScore: di1.score,
    afterScore: di2.score,
    delta,
    improved: delta > 0.05,
    beforeCount: before.length,
    afterCount: after.length
  }
}
