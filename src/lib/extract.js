export function normalize(text) {
  return (text || '')
    .toLowerCase()
    .replace(/ё/g, 'е') // унификация ё→е для матчинга (метки храним с ё)
    .replace(/[^a-zа-я0-9\s-]/gi, ' ')
}

function tokenize(text) {
  return normalize(text)
    .split(/\s+/)
    .map((t) => t.trim())
    .filter((t) => t.length >= 3 && !STOPWORDS.has(t))
}

// корни тоже приводим к е→ё-нейтральной форме
function rootMatch(token, root) {
  return token.startsWith(root.replace(/ё/g, 'е'))
}

function scanCategory(tokens, lexicon) {
  const hits = new Map() // label → count
  for (const token of tokens) {
    for (const entry of lexicon) {
      const [root, label] = entry
      if (rootMatch(token, root)) {
        hits.set(label, (hits.get(label) || 0) + 1)
        break // один токен — одна категория-метка
      }
    }
  }
  return hits
}

function mapToWeighted(hits, extra = {}) {
  return [...hits.entries()]
    .map(([word, count]) => ({ word, count, weight: count, ...extra }))
    .sort((a, b) => b.count - a.count)
}

// Главная функция: вытаскивает все сущности и формирует «вектор дня».
export function extractEntities(text) {
  const tokens = tokenize(text)

  const emoHits = scanCategory(tokens, EMOTIONS)
  // эмоции несут валентность
  const emotions = [...emoHits.entries()].map(([word, count]) => {
    const lex = EMOTIONS.find((e) => e[1] === word)
    return { word, count, weight: count, valence: lex ? lex[2] : 'neutral' }
  }).sort((a, b) => b.count - a.count)

  const colors = mapToWeighted(scanCategory(tokens, COLORS), { category: 'color' })
  const objects = mapToWeighted(scanCategory(tokens, OBJECTS), { category: 'object' })
  const characters = mapToWeighted(scanCategory(tokens, CHARACTERS), { category: 'character' })
  const places = mapToWeighted(scanCategory(tokens, PLACES), { category: 'place' })
  const actions = mapToWeighted(scanCategory(tokens, ACTIONS), { category: 'action' })

  // «прочие» заметные слова, не попавшие в словари — чтобы вектор/пузырь не были пустыми
  const known = new Set()
  ;[emotions, colors, objects, characters, places, actions].forEach((arr) =>
    arr.forEach((x) => known.add(x.word))
  )
  const freq = new Map()
  for (const token of tokens) {
    let matched = false
    for (const lex of [EMOTIONS, COLORS, OBJECTS, CHARACTERS, PLACES, ACTIONS]) {
      if (lex.some((e) => rootMatch(token, e[0]))) { matched = true; break }
    }
    if (!matched && token.length >= 4) freq.set(token, (freq.get(token) || 0) + 1)
  }
  const others = [...freq.entries()]
    .map(([word, count]) => ({ word, count, weight: count, category: 'other' }))
    .sort((a, b) => b.count - a.count)
    .slice(0, 6)

  // вектор дня — все образы с весами и категориями
  const vector = [
    ...objects.map((x) => ({ ...x, category: 'object' })),
    ...characters.map((x) => ({ ...x, category: 'character' })),
    ...places.map((x) => ({ ...x, category: 'place' })),
    ...colors.map((x) => ({ ...x, category: 'color' })),
    ...actions.map((x) => ({ ...x, category: 'action' })),
    ...emotions.map((x) => ({ ...x, category: 'emotion' })),
    ...others
  ]

  return {
    emotions,
    colors,
    objects,
    characters,
    places,
    actions,
    others,
    vector,
    valence: overallValence(emotions)
  }
}

// Общая направленность записи по балансу эмоций.
export function overallValence(emotions) {
  if (!emotions || emotions.length === 0) return 'neutral'
  let neg = 0, res = 0, neu = 0
  for (const e of emotions) {
    if (e.valence === 'negative') neg += e.count
    else if (e.valence === 'resource') res += e.count
    else neu += e.count
  }
  if (neg === 0 && res === 0) return 'neutral'
  if (res > neg) return 'resource'
  if (neg > res) return 'negative'
  return 'neutral'
}

