// safety.js — слой безопасности с правом вето.
// Запускается ПЕРЕД выдачей любой трактовки. Если в записи есть маркеры
// острого кризиса — приложение НЕ выдаёт «красивую» юнгианскую трактовку,
// а мягко возвращает человека к живой помощи.
//
// Это не диагностика и не замена помощи — это аккуратная страховочная сетка.

function norm(text) {
  return (text || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ')
}

// Маркеры высокой остроты — суицидальные мысли, намерение, самоповреждение.
const HIGH_MARKERS = [
  'не хочу жить', 'не хочется жить', 'жить не хочу', 'больше не хочу жить',
  'покончить с собой', 'покончу с собой', 'свести счеты', 'счеты с жизнью',
  'убить себя', 'убью себя', 'хочу умереть', 'хочу сдохнуть', 'лучше умереть',
  'лучше бы я умер', 'лучше бы меня не было', 'лучше не быть',
  'нет смысла жить', 'не вижу смысла жить', 'смысла жить нет', 'жить незачем',
  'самоубий', 'суицид', 'наложить на себя руки',
  'порезать себя', 'режу себя', 'резать себя', 'причинить себе', 'причиняю себе',
  'навредить себе', 'сделать себе больно', 'бью себя',
  'уснуть и не проснуться', 'не проснуться', 'исчезнуть навсегда', 'хочу исчезнуть навсегда'
]

// Маркеры средней остроты — глубокое отчаяние, истощение, ненависть к себе.
const MEDIUM_MARKERS = [
  'все бессмысленно', 'всё бессмысленно', 'ничего не имеет смысла',
  'ненавижу себя', 'я ничтожество', 'я никчемн', 'я никому не нужен', 'никому не нужна',
  'не могу больше', 'сил больше нет', 'сил уже нет', 'на пределе', 'хочу все бросить',
  'все плохо и не изменится', 'безнадежно', 'безысходн'
]

export const CRISIS_RESOURCES = [
  { label: 'Телефон доверия (РФ, круглосуточно, бесплатно)', value: '8-800-2000-122' },
  { label: 'Экстренные службы', value: '112' },
  { label: 'Если ты не в России', value: 'findahelpline.com — найти линию помощи в своей стране' }
]

function contains(text, markers) {
  return markers.some((m) => text.includes(norm(m)))
}

// Главная функция оценки.
export function assessSafety(text) {
  const t = norm(text)
  if (contains(t, HIGH_MARKERS)) {
    return {
      flagged: true,
      veto: true,
      severity: 'high',
      title: 'Сделаем паузу — это важнее любой трактовки',
      message:
        'В твоей записи звучит очень тяжёлая, острая боль. Сейчас не время для символов и архетипов — ' +
        'сейчас важнее, чтобы рядом был живой человек, который тебя выслушает.\n\n' +
        'Пожалуйста, позвони на линию помощи прямо сейчас или напиши тому, кому доверяешь. ' +
        'Ты не обязан проходить через это в одиночку, и то, что ты чувствуешь, можно пережить — с поддержкой это реально.',
      resources: CRISIS_RESOURCES
    }
  }
  if (contains(t, MEDIUM_MARKERS)) {
    return {
      flagged: true,
      veto: false, // трактовку даём, но мягко добавляем поддержку
      severity: 'medium',
      title: 'Я рядом, и хочу кое-что сказать перед трактовкой',
      message:
        'Похоже, сегодня было по-настоящему тяжело. Я растолкую запись, но сначала — простое и важное: ' +
        'если тяжесть не отпускает, поговорить с живым человеком — не слабость, а забота о себе. ' +
        'Линия помощи всегда доступна.',
      resources: CRISIS_RESOURCES
    }
  }
  return { flagged: false, veto: false, severity: null }
}
